-- V7: assistants over MCP — personal and OAuth tokens, OAuth clients/grants/codes, and
-- which entries an assistant recorded.
--
-- Instants are TIMESTAMP WITH TIME ZONE, as everywhere since V1 (see its header).
CREATE TABLE oauth_clients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     VARCHAR(64)   NOT NULL UNIQUE,
    client_name   VARCHAR(200)  NOT NULL,
    redirect_uris VARCHAR(4000) NOT NULL,
    created_at    TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    last_used_at  TIMESTAMP(3) WITH TIME ZONE NULL
);

CREATE TABLE oauth_grants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid       VARCHAR(36)  NOT NULL UNIQUE,
    client_id  BIGINT       NOT NULL REFERENCES oauth_clients (id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scope      VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(3) WITH TIME ZONE NULL
);

CREATE TABLE oauth_codes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash      VARCHAR(64)   NOT NULL UNIQUE,
    grant_id       BIGINT        NOT NULL REFERENCES oauth_grants (id) ON DELETE CASCADE,
    redirect_uri   VARCHAR(1000) NOT NULL,
    code_challenge VARCHAR(128)  NOT NULL,
    expires_at     TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    used_at        TIMESTAMP(3) WITH TIME ZONE NULL
);

CREATE TABLE access_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind           VARCHAR(20)  NOT NULL,          -- PERSONAL | OAUTH_ACCESS | OAUTH_REFRESH
    name           VARCHAR(100) NOT NULL,
    token_hash     VARCHAR(64)  NOT NULL UNIQUE,
    prefix         VARCHAR(10)  NOT NULL,
    oauth_grant_id BIGINT       NULL REFERENCES oauth_grants (id) ON DELETE CASCADE,
    created_at     TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP(3) WITH TIME ZONE NULL,
    last_used_at   TIMESTAMP(3) WITH TIME ZONE NULL,
    used_at        TIMESTAMP(3) WITH TIME ZONE NULL  -- refresh tokens: set when rotated
);
CREATE INDEX idx_access_tokens_user ON access_tokens (user_id);

ALTER TABLE transactions ADD COLUMN source VARCHAR(8) NOT NULL DEFAULT 'APP';

-- A receipt an assistant read itself comes without a photo.
ALTER TABLE receipts ALTER COLUMN image_path DROP NOT NULL;

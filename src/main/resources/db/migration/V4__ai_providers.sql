-- V4: which AI model reads receipts - one for the instance, optionally one per household.
CREATE TABLE ai_providers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope        VARCHAR(20)                 NOT NULL,
    household_id BIGINT                      NULL REFERENCES households (id) ON DELETE CASCADE,
    type         VARCHAR(30)                 NOT NULL,
    base_url     VARCHAR(500)                NULL,
    model        VARCHAR(200)                NOT NULL,
    api_key      VARCHAR(2048)               NULL,
    updated_at   TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ai_provider_household UNIQUE (household_id)
);
-- "One INSTANCE row" would be a partial unique index (ON ai_providers (scope) WHERE scope = 'INSTANCE'),
-- but H2, which the test suite runs on, has no partial indexes, so AiProviderSettings.saveInstance
-- keeps it to one row by updating the existing one.

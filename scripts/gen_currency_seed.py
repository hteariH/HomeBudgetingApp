"""Generate V2__seed_currency_catalog.sql from the Android DefaultCurrencies.kt seed.

Parsing the Kotlin source instead of retyping 104 rows keeps the server catalog
provably identical to the one the Android client already ships. Re-run this whenever
the Android seed changes.
"""
import re
import pathlib

KT = pathlib.Path(
    r"C:\Users\aberk\claude\PersonalMoney\AndroidPersonalMoney\app\src\main\java"
    r"\com\personalmoney\core\database\seed\DefaultCurrencies.kt"
)
OUT = pathlib.Path(
    r"C:\Users\aberk\claude\PersonalMoney\HomeBudgetingApp\src\main\resources"
    r"\db\migration\V2__seed_currency_catalog.sql"
)

src = KT.read_text(encoding="utf-8")

# add("USD", "US Dollar", "$", 2) -- names may contain parentheses, symbols may be escaped
pattern = re.compile(
    r'^\s*add\(\s*"([^"]+)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*(\d+)\s*\)',
    re.MULTILINE,
)

rows = []
for m in pattern.finditer(src):
    code, name, symbol, decimals = m.groups()
    # Kotlin escapes: \$ is a literal dollar sign.
    name = name.replace("\\$", "$").replace('\\"', '"')
    symbol = symbol.replace("\\$", "$").replace('\\"', '"')
    rows.append((code, name, symbol, int(decimals)))

assert len(rows) == 104, f"expected 104 currencies, parsed {len(rows)}"
codes = [r[0] for r in rows]
assert len(set(codes)) == len(codes), "duplicate currency code in seed"
assert max(len(c) for c in codes) <= 10, "currency code longer than VARCHAR(10)"
assert max(len(s) for _, _, s, _ in rows) <= 10, "symbol longer than VARCHAR(10)"
assert max(len(n) for _, n, _, _ in rows) <= 100, "name longer than VARCHAR(100)"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


header = """\
-- V2: the currency catalog, generated from the Android client's DefaultCurrencies.kt
-- so both clients agree on codes, symbols and - critically - decimals.
--
-- Generated by scripts/gen_currency_seed.py; edit the Android seed and re-run rather
-- than editing this file by hand.
--
-- exchange_rate_to_base is left at 1.0 for every row: it is the legacy single-rate
-- column the React client still reads, and real rates now live in exchange_rates,
-- refreshed from Frankfurter.
INSERT INTO currencies (code, name, symbol, decimals, exchange_rate_to_base, is_base, sort_order) VALUES
"""

values = []
for i, (code, name, symbol, decimals) in enumerate(rows):
    is_base = "TRUE" if code == "USD" else "FALSE"
    values.append(
        f"    ({q(code)}, {q(name)}, {q(symbol)}, {decimals}, 1.000000, {is_base}, {i})"
    )

OUT.write_text(header + ",\n".join(values) + ";\n", encoding="utf-8")
print(f"wrote {OUT} with {len(rows)} currencies")
print("0-decimal:", [c for c, _, _, d in rows if d == 0])
print("3+decimal:", [(c, d) for c, _, _, d in rows if d >= 3])

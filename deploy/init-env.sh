#!/usr/bin/env bash
#
# Creates /opt/homebudget/.env with freshly generated secrets.
#
# Run this ON THE VPS. The random values are produced here and never leave the machine,
# which is the point: a secret that has travelled through a chat log, a terminal on a
# laptop or a CI variable has more copies than you can account for.
#
#   scp deploy/init-env.sh <vps>:/tmp/ && ssh <vps> 'sudo bash /tmp/init-env.sh'
#
set -euo pipefail

TARGET_DIR=/opt/homebudget
TARGET="$TARGET_DIR/.env"

# Refuse rather than regenerate. Overwriting CRYPTO_SECRET silently makes every stored
# bank connection unreadable, and that is not something to discover later.
if [ -f "$TARGET" ]; then
    echo "ERROR: $TARGET already exists." >&2
    echo "Regenerating it would change CRYPTO_SECRET and make stored bank" >&2
    echo "connections unreadable. Edit the file by hand instead." >&2
    exit 1
fi

command -v openssl >/dev/null || { echo "ERROR: openssl is required" >&2; exit 1; }

read -rp "Resend API key (re_...): " MAIL_PASSWORD
if [ -z "${MAIL_PASSWORD:-}" ]; then
    echo "ERROR: the Resend key is required; mail will not send without it" >&2
    exit 1
fi

read -rp "Mail from [noreply@personalmoney.app]: " MAIL_FROM
MAIL_FROM="${MAIL_FROM:-noreply@personalmoney.app}"

read -rp "Public base URL [https://personalmoney.app]: " APP_BASE_URL
APP_BASE_URL="${APP_BASE_URL:-https://personalmoney.app}"

# Nothing outside this file ever needs to know the database passwords, so they may as
# well be random.
DB_PASSWORD=$(openssl rand -base64 24)
DB_ROOT_PASSWORD=$(openssl rand -base64 24)
JWT_SECRET=$(openssl rand -base64 32)
CRYPTO_SECRET=$(openssl rand -base64 32)

mkdir -p "$TARGET_DIR"
umask 077
cat > "$TARGET" <<ENVFILE
# Generated by deploy/init-env.sh. Deploys never overwrite this file.
#
# Back the two secrets below up to a password manager. GitHub secrets cannot be read
# back, and this file dies with the disk.

DB_USERNAME=homebudget
DB_PASSWORD=$DB_PASSWORD
DB_ROOT_PASSWORD=$DB_ROOT_PASSWORD

# Signs access tokens. Rotating it signs everyone out - annoying, not harmful.
JWT_SECRET=$JWT_SECRET

# Encrypts stored bank credentials. NEVER rotate: doing so makes existing bank
# connections unreadable and every user has to reconnect.
CRYPTO_SECRET=$CRYPTO_SECRET

APP_BASE_URL=$APP_BASE_URL

MAIL_HOST=smtp.resend.com
MAIL_PORT=587
MAIL_USERNAME=resend
MAIL_PASSWORD=$MAIL_PASSWORD
MAIL_FROM=$MAIL_FROM
ENVFILE

chmod 600 "$TARGET"
echo
echo "Wrote $TARGET (chmod 600)."
echo
echo "Copy these two into a password manager now - CRYPTO_SECRET cannot be recovered:"
echo
grep -E '^(JWT_SECRET|CRYPTO_SECRET)=' "$TARGET"
echo
echo "They are printed once, here, and nowhere else."
